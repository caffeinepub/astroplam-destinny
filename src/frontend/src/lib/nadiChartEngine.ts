const D2R = Math.PI / 180;
const R2D = 180 / Math.PI;
const TWO_PI = 2 * Math.PI;

// ─── Helpers ─────────────────────────────────────────────────────────────────
function sinD(d: number) {
  return Math.sin(d * D2R);
}
function cosD(d: number) {
  return Math.cos(d * D2R);
}
function atan2D(y: number, x: number) {
  return Math.atan2(y, x) * R2D;
}
function acosD(x: number) {
  return Math.acos(x) * R2D;
}

function norm360(v: number): number {
  let r = v % 360;
  if (r < 0) r += 360;
  return r;
}

// ─── Julian Day ───────────────────────────────────────────────────────────────
export function nadiJulianDay(
  year: number,
  month: number,
  day: number,
  utHour: number,
): number {
  let y = year;
  let m = month;
  if (m <= 2) {
    y--;
    m += 12;
  }
  const A = Math.floor(y / 100);
  const B = 2 - A + Math.floor(A / 4);
  return (
    Math.floor(365.25 * (y + 4716)) +
    Math.floor(30.6001 * (m + 1)) +
    day +
    B -
    1524.5 +
    utHour / 24
  );
}

function julianCenturies(jd: number): number {
  return (jd - 2451545.0) / 36525;
}

// ─── Obliquity & Nutation ─────────────────────────────────────────────────────
function obliquity(T: number): number {
  return (
    23.439291111 -
    0.013004167 * T -
    0.0000001639 * T * T +
    0.0000005036 * T * T * T
  );
}

function calcNutation(T: number): { dPsi: number; dEps: number } {
  const omega = norm360(125.04452 - 1934.136261 * T + 0.0020708 * T * T);
  const L = norm360(280.4665 + 36000.7698 * T);
  const Lp = norm360(218.3165 + 481267.8813 * T);
  const dPsiAs =
    (-17.2 - 0.01742 * T) * sinD(omega) +
    -1.32 * sinD(2 * L) +
    -0.23 * sinD(2 * Lp) +
    0.21 * sinD(2 * omega);
  const dEpsAs =
    (9.2 + 0.00089 * T) * cosD(omega) +
    0.57 * cosD(2 * L) +
    0.1 * cosD(2 * Lp) +
    -0.09 * cosD(2 * omega);
  return { dPsi: dPsiAs / 3600, dEps: dEpsAs / 3600 };
}

// ─── KP Ayanamsa (Lahiri + 6 arcminutes) ─────────────────────────────────────
function lahiriAyanamsa(jd: number): number {
  const T = (jd - 2451545.0) / 36525.0;
  const ayan = 23.853167 + (5029.1 / 3600.0) * T;
  return norm360(ayan);
}

function computeKPAyanamsa(jd: number): number {
  return norm360(lahiriAyanamsa(jd) + 0.1); // +6 arcmin = +0.1°
}

// ─── VSOP87B Series Evaluation ────────────────────────────────────────────────
function vsopSeries(series: number[][], tau: number): number {
  let sum = 0;
  for (const [A, B, C] of series) {
    sum += A * Math.cos(B + C * tau);
  }
  return sum;
}

function vsopL(coeffs: number[][][], tau: number): number {
  let L = 0;
  let tauPow = 1;
  for (const series of coeffs) {
    L += vsopSeries(series, tau) * tauPow;
    tauPow *= tau;
  }
  return L;
}

function vsopR(coeffs: number[][][], tau: number): number {
  let R = 0;
  let tauPow = 1;
  for (const series of coeffs) {
    R += vsopSeries(series, tau) * tauPow;
    tauPow *= tau;
  }
  return R;
}

