// ─── Main Chart Calculation ───────────────────────────────────────────────────
export function calculateNadiChart(
  year: number,
  month: number,
  day: number,
  hour: number,
  minute: number,
  lat: number,
  lon: number,
  timezone: number,
  place = "",
): NadiChartResult {
  // Convert local time to UT
  let utHour = hour + minute / 60 - timezone;
  let utDay = day;
  let utMonth = month;
  let utYear = year;
  if (utHour < 0) {
    utHour += 24;
    utDay--;
    if (utDay === 0) {
      utMonth--;
      if (utMonth === 0) {
        utMonth = 12;
        utYear--;
      }
      const dIM = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
      utDay =
        utMonth === 2 &&
        ((utYear % 4 === 0 && utYear % 100 !== 0) || utYear % 400 === 0)
          ? 29
          : dIM[utMonth];
    }
  } else if (utHour >= 24) {
    utHour -= 24;
    utDay++;
    const dIM2 = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
    const maxDay =
      utMonth === 2 &&
      ((utYear % 4 === 0 && utYear % 100 !== 0) || utYear % 400 === 0)
        ? 29
        : dIM2[utMonth];
    if (utDay > maxDay) {
      utDay = 1;
      utMonth++;
      if (utMonth > 12) {
        utMonth = 1;
        utYear++;
      }
    }
  }

  const jd = nadiJulianDay(utYear, utMonth, utDay, utHour);
  const T = julianCenturies(jd);
  const ayanamsa = computeKPAyanamsa(jd);
  const eps = obliquity(T);
  const LMST = norm360(gmst(jd) + lon);
  const { dPsi, dEps } = calcNutation(T);
  const epsApp = eps + dEps;
  const LMSTApp = norm360(LMST + dPsi * Math.cos(eps * D2R));
  const tropCusps = placidusHouseCusps(LMSTApp, epsApp, lat);
  const sidCusps = tropCusps.map((c) => norm360(c - ayanamsa));

  function toSid(trop: number) {
    return norm360(trop - ayanamsa);
  }

  const lagnaSign = Math.floor(sidCusps[0] / 30);

  // Compute raw planet positions
  const { dPsi: dPsiNut } = calcNutation(T);
  const planetNames = [
    "Sun",
    "Moon",
    "Mars",
    "Mercury",
    "Jupiter",
    "Venus",
    "Saturn",
    "Uranus",
    "Neptune",
    "Pluto",
  ];
  const planetAbbrs = [
    "Su",
    "Mo",
    "Ma",
    "Me",
    "Ju",
    "Ve",
    "Sa",
    "Ur",
    "Ne",
    "Pl",
  ];

  const rahuTrop = norm360(rahuMeanNode(jd) + dPsiNut);
  const ketuTrop = norm360(rahuTrop + 180);

  const rawResults: Array<{
    name: string;
    abbr: string;
    tropLon: number;
    retro: boolean;
  }> = [];

  for (let i = 0; i < planetNames.length; i++) {
    const res = getPlanetGeocentricLon(planetNames[i], jd);
    rawResults.push({
      name: planetNames[i],
      abbr: planetAbbrs[i],
      tropLon: norm360(res.lon + dPsiNut),
      retro: res.retrograde,
    });
  }

  rawResults.push({ name: "Rahu", abbr: "Ra", tropLon: rahuTrop, retro: true });
  rawResults.push({ name: "Ketu", abbr: "Ke", tropLon: ketuTrop, retro: true });

  const moonTrop = rawResults.find((p) => p.name === "Moon")!.tropLon;
  const moonSid = toSid(moonTrop);

  const planets: NadiPlanetData[] = rawResults.map((p) => {
    const sid = toSid(p.tropLon);
    const sign = Math.floor(sid / 30);
    const degrees = sid % 30;
    const nak = getNakshatraInfo(sid);
    const subLord = getSubLord(sid);
    const house = findKPHouse(sid, sidCusps);
    const natalHouse = ((sign - lagnaSign + 12) % 12) + 1;
    return {
      name: p.name,
      abbr: p.abbr,
      tropLon: p.tropLon,
      sidLon: sid,
      sign,
      signName: NADI_SIGNS[sign],
      degrees,
      nakshatra: nak.name,
      pada: nak.pada,
      nakshatraLord: nak.lord,
      subLord,
      retrograde: p.retro,
      natalHouse,
      bhavaHouse: house,
    };
  });

  const ascSid = sidCusps[0];
  const ascSign = Math.floor(ascSid / 30);
  const ascNak = getNakshatraInfo(ascSid);
  const ascendant: NadiPlanetData = {
    name: "Ascendant",
    abbr: "As",
    tropLon: tropCusps[0],
    sidLon: ascSid,
    sign: ascSign,
    signName: NADI_SIGNS[ascSign],
    degrees: ascSid % 30,
    nakshatra: ascNak.name,
    pada: ascNak.pada,
    nakshatraLord: ascNak.lord,
    subLord: getSubLord(ascSid),
    retrograde: false,
    natalHouse: 1,
    bhavaHouse: 1,
  };

  const birthDate = new Date(year, month - 1, day, hour, minute);
  const dasha = calculateNadiDasha(birthDate, moonSid);

  return {
    planets,
    ascendant,
    dasha,
    ayanamsa,
    inputDate: `${String(day).padStart(2, "0")}-${String(month).padStart(2, "0")}-${year}`,
    inputTime: `${String(hour).padStart(2, "0")}:${String(minute).padStart(2, "0")}`,
    inputPlace: place,
  };
}
